#!/usr/bin/env bash

set -euo pipefail

# resolve dir
REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

usage() {
	cat <<EOF
Usage: install.sh [--bash] [--ai] [--tools] [--all] [--uninstall] [--dry-run] [-h]
  --bash       add loader to ~/.bashrc
  --ai         link ai/AGENTS.md into each agent's global config (Claude Code, Goose, Cursor)
  --tools      apt install the tools in tools.txt (needs sudo; not part of --all)
  --all        --bash and --ai (default when no step flags given)
  --uninstall  undo the selected steps (default: --bash and --ai)
  --dry-run    print what would change, change nothing
EOF
}

DO_BASH=0
DO_AI=0
DO_TOOLS=0
UNINSTALL=0
DRY_RUN=0
for arg in "$@"; do
	case "$arg" in
		--bash)      DO_BASH=1 ;;
		--ai)        DO_AI=1 ;;
		--tools)     DO_TOOLS=1 ;;
		--all)       DO_BASH=1; DO_AI=1 ;;
		--uninstall) UNINSTALL=1 ;;
		--dry-run)   DRY_RUN=1 ;;
		-h|--help)   usage; exit 0 ;;
		*) echo "Unknown option: $arg" >&2; usage >&2; exit 1 ;;
	esac
done

# no step flags -> bash + ai
if [ $((DO_BASH + DO_AI + DO_TOOLS)) -eq 0 ]; then
	DO_BASH=1
	DO_AI=1
fi

STAMP="$(date +%Y%m%d%H%M%S)"
MARKER_START="# >>> dotfiles-loader >>>"
MARKER_END="# <<< dotfiles-loader <<<"

# every change goes through run so --dry-run can print instead
run() {
	if [ "$DRY_RUN" -eq 1 ]; then
		echo "[dry-run] $*"
	else
		"$@"
	fi
}

# --- bash ---

install_bash() {
	local loader_file="$REPO_DIR/bash/loader.sh"
	local bashrc="$HOME/.bashrc"

	if [ ! -f "$loader_file" ]; then
		echo "Error: Could not find $loader_file" >&2
		exit 1
	fi

	if [ -f "$bashrc" ] && grep -Fq "$MARKER_START" "$bashrc"; then
		echo "Dotfiles loader already configured in $bashrc"
		return
	fi

	run touch "$bashrc"
	run cp "$bashrc" "${bashrc}.bak.$STAMP"
	if [ "$DRY_RUN" -eq 1 ]; then
		echo "[dry-run] append loader block to $bashrc"
	else
		cat <<EOF >> "$bashrc"

$MARKER_START
[ -r "$loader_file" ] && source "$loader_file"
$MARKER_END
EOF
	fi
	echo "Backed up $bashrc and added dotfiles loader."
}

uninstall_bash() {
	local bashrc="$HOME/.bashrc"

	if [ ! -f "$bashrc" ] || ! grep -Fq "$MARKER_START" "$bashrc"; then
		echo "No dotfiles loader in $bashrc"
		return
	fi

	run cp "$bashrc" "${bashrc}.bak.$STAMP"
	if [ "$DRY_RUN" -eq 1 ]; then
		echo "[dry-run] remove loader block from $bashrc"
	else
		local tmp
		tmp="$(mktemp)"
		sed "/^$MARKER_START\$/,/^$MARKER_END\$/d" "$bashrc" > "$tmp"
		cat "$tmp" > "$bashrc"
		rm -f "$tmp"
	fi
	echo "Removed dotfiles loader from $bashrc (backup: ${bashrc}.bak.$STAMP)"
}

# --- ai ---

AGENTS_SRC="$REPO_DIR/ai/AGENTS.md"
# global instruction files that can be a plain symlink to AGENTS.md
AI_LINKS=(
	"$HOME/.claude/CLAUDE.md"
	"$HOME/.config/goose/.goosehints"
)
# Cursor rule files need frontmatter, so this one is a generated copy, not a link
CURSOR_RULE="$HOME/.cursor/rules/global-agents.mdc"
CURSOR_TAG="generated by dotfiles/install.sh"

backup_if_present() {
	local dst="$1"
	if [ -e "$dst" ] || [ -L "$dst" ]; then
		run mv "$dst" "${dst}.bak.$STAMP"
		echo "Backed up existing $dst"
	fi
}

link_file() {
	local src="$1" dst="$2"

	if [ -L "$dst" ] && [ "$(readlink "$dst")" = "$src" ]; then
		echo "Already linked: $dst"
		return
	fi
	run mkdir -p "$(dirname "$dst")"
	backup_if_present "$dst"
	run ln -s "$src" "$dst"
	echo "Linked $dst -> $src"
}

write_cursor_rule() {
	# only replace a file we generated; back up anything else
	if [ -f "$CURSOR_RULE" ] && ! grep -Fq "$CURSOR_TAG" "$CURSOR_RULE"; then
		backup_if_present "$CURSOR_RULE"
	fi
	run mkdir -p "$(dirname "$CURSOR_RULE")"
	if [ "$DRY_RUN" -eq 1 ]; then
		echo "[dry-run] write $CURSOR_RULE from $AGENTS_SRC"
	else
		{
			printf -- '---\ndescription: Global agent rules (%s; edit ai/AGENTS.md and rerun --ai)\nalwaysApply: true\n---\n\n' "$CURSOR_TAG"
			cat "$AGENTS_SRC"
		} > "$CURSOR_RULE"
	fi
	echo "Wrote $CURSOR_RULE"
}

install_ai() {
	if [ ! -f "$AGENTS_SRC" ]; then
		echo "Error: Could not find $AGENTS_SRC" >&2
		exit 1
	fi
	local dst
	for dst in "${AI_LINKS[@]}"; do
		link_file "$AGENTS_SRC" "$dst"
	done
	write_cursor_rule
}

uninstall_ai() {
	local dst
	for dst in "${AI_LINKS[@]}"; do
		# only remove links that point into this repo
		if [ -L "$dst" ] && [ "$(readlink "$dst")" = "$AGENTS_SRC" ]; then
			run rm "$dst"
			echo "Removed link $dst"
		fi
	done
	if [ -f "$CURSOR_RULE" ] && grep -Fq "$CURSOR_TAG" "$CURSOR_RULE"; then
		run rm "$CURSOR_RULE"
		echo "Removed $CURSOR_RULE"
	fi
}

# --- tools ---

install_tools() {
	local manifest="$REPO_DIR/tools.txt"
	local pkgs=() name apt choco

	if ! command -v apt-get >/dev/null 2>&1; then
		echo "Error: --tools needs apt-get (Debian/Ubuntu/WSL)." >&2
		exit 1
	fi
	while read -r name apt choco; do
		case "$name" in ''|\#*) continue ;; esac
		[ "$apt" != "-" ] && pkgs+=("$apt")
	done < "$manifest"

	echo "Installing: ${pkgs[*]}"
	run sudo apt-get update
	run sudo apt-get install -y "${pkgs[@]}"
	if ! command -v uv >/dev/null 2>&1; then
		echo "uv is not in apt; install it with: curl -LsSf https://astral.sh/uv/install.sh | sh"
	fi
}

# --- main ---

if [ "$UNINSTALL" -eq 1 ]; then
	[ "$DO_BASH" -eq 1 ] && uninstall_bash
	[ "$DO_AI" -eq 1 ] && uninstall_ai
	[ "$DO_TOOLS" -eq 1 ] && echo "--tools uninstall is not supported; remove packages with apt."
	echo "Backups (*.bak.*) were left in place."
	echo "Done!"
	exit 0
fi

[ "$DO_BASH" -eq 1 ] && install_bash
[ "$DO_AI" -eq 1 ] && install_ai
[ "$DO_TOOLS" -eq 1 ] && install_tools

echo "Done!"
if [ "$DO_BASH" -eq 1 ]; then
	echo "Run 'source ~/.bashrc' to apply your config."
fi
